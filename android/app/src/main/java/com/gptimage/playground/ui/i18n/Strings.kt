fun AppLanguage.toStrings(): Strings = when (this) {
    AppLanguage.SIMPLIFIED_CHINESE -> ChineseStrings
    AppLanguage.ENGLISH -> EnglishStrings
    AppLanguage.SYSTEM -> ChineseStrings // The default app locale is Chinese; resolved by the host in real time.
}

val LocalStrings = staticCompositionLocalOf { ChineseStrings }

@Composable
@ReadOnlyComposable
fun strings(): Strings = LocalStrings.current
